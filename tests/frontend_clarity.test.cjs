// Behavioral checks for the new operator guidance; no live Wolfram/USB claims.
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const elements=new Map();
const element=id=>{if(!elements.has(id))elements.set(id,{style:{},querySelectorAll:()=>[],setAttribute(n,v){this[n]=v},removeAttribute(n){delete this[n]}});return elements.get(id)};
const requests=[];
const context=vm.createContext({document:{getElementById:element,querySelectorAll:()=>[]},URLSearchParams,setInterval:()=>1,fetch:async(url,opts)=>{requests.push([url,opts]);return new Promise(()=>{})}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../stratus/inspection/web/app.js'),'utf8'),context);
const run=source=>vm.runInContext(source,context);
run("state={run:{aircraft_state:{revision:0,actions_remaining:3},review_revision:0,plan_history:[],feedback:[],events:[]},current_plan:null};workflowView()");
assert.equal(element('execute-plan').disabled,true);
assert.match(element('execution-help').textContent,/Review next action/);
assert.equal(element('step-plan')['aria-current'],'step');
run("state.current_plan={plan_id:'ready',proposal:{asset_id:'P03',view_id:'overview'},state_revision:0,review_revision:0,ground_context_id:'ground-test',computation:{execution_permitted:true},execution_mode:'deterministic_rule_based'};armedPlanId='ready';workflowView()");
assert.equal(element('execute-plan').disabled,false);
assert.equal(element('step-capture')['aria-current'],'step');
run("state.current_plan.computation.execution_permitted=false;workflowView()");
assert.equal(element('execute-plan').disabled,true);
assert.match(element('execution-help').textContent,/disagreement blocks execution/);
console.log('PASS: proposal review and numerical permission control execution guidance');
run("state.run.aircraft_state.actions_remaining=0;armedPlanId=null;workflowView()");
assert.match(element('execution-help').textContent,/All three capture actions are used/);
assert.match(element('journey-help').textContent,/Fresh mission/);
assert.equal(element('step-save')['aria-current'],'step');
console.log('PASS: an exhausted run has a concrete save/review/restart path');
assert.match(run("calculationHelp('wolfram_local')"),/Actual local Wolfram/);
assert.match(run("calculationHelp('cached_wolfram_local')"),/exact inputs/);
assert.match(run("calculationHelp('local_python_fallback')"),/no live Wolfram success/);
assert.match(run("calculationHelp('wolfram_disagreement')"),/blocked/);
console.log('PASS: actual, cached, local and unavailable Wolfram modes remain distinct');
run("ground({mode:'recorded_measured',source_label:'Recorded',sensors:[{sensor_model:'PMSA003I',status:'stale',age_seconds:90,channels:[{variable:'pm2_5',value:0,unit:'ug/m3',acquired_at_utc:'2026-11-14T12:00:00+00:00'}]}],node_id:'ground-node-001',location:{label:null},observations:[{value:0}]})");
assert.match(element('sensor-readings').innerHTML,/>0.00</);
assert.match(element('sensor-readings').innerHTML,/2026-11-14T12:00:00/);
assert.match(element('ground-source-help').textContent,/Refresh does not make them new/);
assert.match(element('ground-meta').textContent,/Location not supplied/);
run("ground({mode:'unavailable',source_label:'Unavailable',sensors:[{sensor_model:'BME280',status:'unavailable',age_seconds:null,channels:[{variable:'temperature',value:null,unit:'degC'}]}],location:{label:null},observations:[]})");
assert.match(element('sensor-readings').innerHTML,/>\u2014</);
assert.equal(element('export-ground').disabled,true);
console.log('PASS: recorded zero, original time and unavailable dash are not conflated');
const count=requests.length;
run("state.run.aircraft_state.actions_remaining=3;state.current_plan=null;workflowView();journey()");
assert.equal(requests.length,count);
assert.equal(requests.some(([url])=>url==='/api/execute'),false);
console.log('PASS: rendering guidance, costs and source labels cannot execute a capture');
run("loadingMission=true;document.getElementById('load').onclick()");
assert.equal(requests.some(([url])=>url==='/api/load'),false);
run("loadingMission=false;document.getElementById('checkpoint').value='saved.json';document.getElementById('load').onclick();document.getElementById('load').onclick()");
assert.equal(requests.filter(([url])=>url==='/api/load').length,1);
assert.equal(element('load').disabled,true);
console.log('PASS: initial and duplicate mission loads cannot race the saved-run selector');
